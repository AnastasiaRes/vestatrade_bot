"""Границы зоны консультации: что бот подбирает, а что только показывает.

В фиде примерно четверть позиций относится к семействам, для которых у бота нет
ни инженерных правил подбора, ни контракта уточнений: смесители, полотенцесушители,
дымоходы, теплоизоляция, крепёж, инструмент. Категории у них тоже нет — они
попадают в служебную «other».

Без явной границы это приводило к худшему из возможных поведений: роутер
присваивал запросу ближайшую поддержанную категорию, и покупатель получал не
предупреждение, а **товар другого семейства**. На «полотенцесушитель водяной
500х600» бот выдавал стальные панельные радиаторы 500x600 — размер совпадал,
изделие было другим.

Правило здесь одно: если семейство вне зоны подбора, об этом говорится прямо.
Позиции при этом не скрываются — они есть в каталоге, и их можно показать как
результат поиска по названию, но без инженерных обещаний.
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class UnsupportedFamily:
    """Семейство товаров, которое бот показывает, но не подбирает."""

    key: str
    # Как называть семейство в ответе покупателю.
    title: str
    pattern: str


# Порядок важен: «смеситель для ванны» — это смеситель, а не ванна.
UNSUPPORTED_FAMILIES: tuple[UnsupportedFamily, ...] = (
    UnsupportedFamily("mixers", "смесители", r"смесител\w*"),
    UnsupportedFamily(
        "towel_dryers", "полотенцесушители", r"полотенцесушител\w*|полотенцесуш\w*"
    ),
    UnsupportedFamily(
        "chimneys",
        "дымоходы и коаксиальные комплекты",
        r"дымоход\w*|коаксиальн\w*",
    ),
    UnsupportedFamily(
        "insulation",
        "теплоизоляция",
        # Только запрос товара. «Утеплителя ещё нет», «пол не утеплён» —
        # это факт о состоянии объекта в воронке тёплого пола, а не покупка.
        r"теплоизоляц\w*|изоляц\w*\s+для\s+труб|"
        r"утеплител\w*\s+для\s+труб|трубн\w*\s+утеплител\w*",
    ),
    UnsupportedFamily(
        "fasteners", "крепёж", r"\bкрепеж\w*|\bхомут\w*|кронштейн\w*|шпильк\w*"
    ),
    UnsupportedFamily(
        "tools",
        "инструмент",
        r"\bинструмент\w*|сварочн\w*\s+аппарат|\bпаяльник\w*|"
        r"труборез\w*|ножниц\w*\s+для\s+труб",
    ),
    UnsupportedFamily(
        # «Унитаз» здесь безопасен: проект установки прибора разбирается
        # раньше в диалоге, поэтому сюда доходит именно запрос товара.
        "sanitary_ware",
        "санфаянс",
        r"раковин\w*|умывальник\w*|мойк\w*|унитаз\w*|биде\b|инсталляц\w*",
    ),
)


# Семейства, которые бот ведёт полноценно. Если такое существительное стоит
# главным в реплике, вопрос всё-таки о нём.
SUPPORTED_HEAD_NOUNS_RE = re.compile(
    r"\b(?:кран\w*|вентил\w*|клапан\w*|котел\w*|котл\w*|насос\w*|радиатор\w*|"
    r"батаре\w*|водонагрев\w*|бойлер\w*|труб\w*|фитинг\w*|муфт\w*|тройник\w*|"
    r"угольник\w*|уголок|уголк\w*|фильтр\w*|коллектор\w*|гребенк\w*|"
    r"термоголов\w*|термостат\w*)\b"
)

# «Дымоход ДЛЯ газового котла», «смеситель ДЛЯ ванны» — то, что стоит после
# предлога, уточняет задачу, а не называет искомый товар.
_QUALIFIER_RE = re.compile(
    r"\b(?:для|к|под|на|от|перед|возле|рядом\s+с|у)\s+[^,.;]{0,32}"
)


def match_unsupported_family(text: str) -> UnsupportedFamily | None:
    """Семейство вне зоны подбора, если покупатель спрашивает именно о нём.

    ``text`` ожидается уже нормализованным (``normalize_text``).
    """

    if not text:
        return None
    # Слово внутри уточнения называет место или задачу, а не товар: «под
    # раковиной треснула труба» — это запрос трубы, а не раковины.
    qualifier_spans = [
        (match.start(), match.end()) for match in _QUALIFIER_RE.finditer(text)
    ]

    def names_the_product(match: re.Match[str]) -> bool:
        return not any(
            start <= match.start() < end for start, end in qualifier_spans
        )

    family = next(
        (
            item
            for item in UNSUPPORTED_FAMILIES
            if any(
                names_the_product(match) for match in re.finditer(item.pattern, text)
            )
        ),
        None,
    )
    if family is None:
        return None
    # Главное существительное поддержанного семейства перевешивает: в запросе
    # «кран для полотенцесушителя» покупателю нужен кран.
    head_text = _QUALIFIER_RE.sub(" ", text)
    if SUPPORTED_HEAD_NOUNS_RE.search(head_text):
        return None
    return family
